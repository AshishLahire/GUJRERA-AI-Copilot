"""Cited promoter, project and agent profiles built from registry records.

Each sentence is a template from ``gujrera.i18n`` filled with values read from
the repository, and carries the records it came from. Nothing here is
generated by a model, so a profile cannot state a fact the records do not hold.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from gujrera.db.repository import Repository
from gujrera.i18n import fmt_date, t, word

ADVERSE_ORDERS = ("show_cause", "penalty_order", "revocation_order")


@dataclass
class Sentence:
    text: str
    citations: list[dict[str, Any]]
    key: str


@dataclass
class Profile:
    kind: str  # project | promoter | agent
    entity_id: str
    title: str
    sentences: list[Sentence] = field(default_factory=list)
    card: dict[str, Any] = field(default_factory=dict)
    is_mock: bool = False

    def add(self, key: str, lang: str, citations: list[dict[str, Any]], **values: Any) -> None:
        self.sentences.append(Sentence(t(key, lang, **values), citations, key))


def _name(row: dict[str, Any], lang: str) -> str:
    return (row.get("name_gu") if lang == "gu" else None) or row["name"]


def project_profile(repo: Repository, project_id: int, lang: str, *, focus: str | None = None) -> Profile | None:
    """Full project profile, or just the possession answer when ``focus == "possession"``."""
    p = repo.get_project_by_id(project_id)
    if p is None:
        return None
    src = p["source"]
    promoter = repo.get_promoter(p["promoter_id"])
    prof = Profile("project", p["rera_no"], _name(p, lang), is_mock=src["is_mock"])
    prof.card = {
        "type": "project", "project_id": p["id"], "name": p["name"], "name_gu": p.get("name_gu"), "rera_no": p["rera_no"],
        "promoter_id": p["promoter_id"], "promoter_name": p["promoter_name"], "district": p["district"],
        "status": p["status"], "reg_valid_until": p["reg_valid_until"],
        "proposed_completion": p["proposed_completion"], "revised_completion": p["revised_completion"],
        "actual_completion": p["actual_completion"], "delay_days": p["delay_days"], "is_mock": src["is_mock"],
        "source": src,
    }

    if focus != "possession":
        if promoter.get("promoter_type") == "unknown":  # imported public record without a promoter name
            prof.add("project_intro_nopromoter", lang, [src], name=_name(p, lang),
                     ptype=word(p["project_type"], lang), district=word(p["district"], lang), rera=p["rera_no"])
        else:
            prof.add("project_intro", lang, [src, promoter["source"]], name=_name(p, lang),
                     ptype=word(p["project_type"], lang), promoter=_name(promoter, lang),
                     district=word(p["district"], lang), rera=p["rera_no"])
        prof.add("project_status", lang, [src], status=word(p["status"], lang),
                 valid=fmt_date(p["reg_valid_until"], lang))

    if p["actual_completion"]:
        prof.add("completed_on", lang, [src], date=fmt_date(p["actual_completion"], lang))
    else:
        prof.add("completion_date", lang, [src], date=fmt_date(p["reg_valid_until"], lang))
        if p["revised_completion"] and p["revised_completion"] != p["proposed_completion"]:
            prof.add("completion_extended", lang, [src], orig=fmt_date(p["proposed_completion"], lang),
                     revised=fmt_date(p["revised_completion"], lang))
    if p["status"] == "unverified":
        prof.add("completion_unverified", lang, [src])
    elif p["delay_days"] > 0 and not p["actual_completion"]:
        prof.add("delay", lang, [src], days=p["delay_days"])

    progress = repo.project_progress(project_id)
    filed = [r for r in progress if r["filed_on"]]
    if filed:
        last = filed[-1]
        prof.add("progress", lang, [last["source"]], quarter=last["quarter"], pct=f"{last['percent_complete']:g}")
    missed = [r for r in progress if not r["filed_on"]]
    if missed and focus != "possession":
        prof.add("qpr_missed", lang, [missed[-1]["source"]], n=len(missed))

    if focus == "possession":
        return prof

    pending = [a for a in repo.project_approvals(project_id) if a["status"] == "pending"]
    if pending:
        prof.add("approvals_pending", lang, [a["source"] for a in pending],
                 items=", ".join(word(a["kind"], lang) for a in pending))
    counts = repo.complaint_counts(project_id=project_id)
    if counts["total"]:
        prof.add("complaints", lang, [counts["source"]], total=counts["total"], open=counts["open"])
    else:
        prof.add("no_complaints", lang, [src])
    prof.card["complaints_total"], prof.card["complaints_open"] = counts["total"], counts["open"]
    return prof


def promoter_profile(repo: Repository, promoter_id: int, lang: str) -> Profile | None:
    promoter = repo.get_promoter(promoter_id)
    card = repo.promoter_scorecard(promoter_id)
    if promoter is None or card is None:
        return None
    src = promoter["source"]
    projects = repo.promoter_projects(promoter_id)
    prof = Profile("promoter", str(promoter_id), _name(promoter, lang), is_mock=src["is_mock"])
    ongoing = sum(p["status"] == "ongoing" for p in projects)
    completed = sum(p["status"] == "completed" for p in projects)
    project_sources = [p["source"] for p in projects]

    prof.add("promoter_intro", lang, [src, *project_sources], name=_name(promoter, lang), n=len(projects),
             ongoing=ongoing, completed=completed)
    if card["delayed_projects"]:
        prof.add("promoter_delayed", lang, [card["source"]],
                 d=card["delayed_projects"], max=card["max_delay_days"])
    else:
        prof.add("promoter_no_delay", lang, [card["source"]])
    counts = repo.complaint_counts(promoter_id=promoter_id)
    if counts["total"]:
        prof.add("promoter_complaints", lang, [counts["source"]], total=counts["total"], open=counts["open"])
    else:
        prof.add("no_complaints", lang, [src])
    orders = [o for o in repo.list_orders(promoter_id=promoter_id) if o["order_type"] in ADVERSE_ORDERS]
    if orders:
        prof.add("promoter_orders", lang, [o["source"] for o in orders], n=len(orders))
        latest = orders[0]
        # Order summaries are stored in English; shown as written.
        prof.add("latest_order", lang, [latest["source"]], date=fmt_date(latest["issued_on"], lang),
                 summary=latest["summary"])
    else:
        prof.add("promoter_no_orders", lang, [src])

    prof.card = {
        "type": "promoter", "id": promoter_id, "name": promoter["name"], "name_gu": promoter.get("name_gu"),
        "district": promoter["district"], "projects": card["projects"],
        "delayed_projects": card["delayed_projects"], "max_delay_days": card["max_delay_days"],
        "complaints_total": counts["total"], "complaints_open": counts["open"],
        "adverse_orders": card["adverse_orders"], "is_mock": src["is_mock"], "source": src,
        "project_list": [
            {"name": p["name"], "rera_no": p["rera_no"], "district": p["district"], "status": p["status"],
             "delay_days": p["delay_days"], "reg_valid_until": p["reg_valid_until"]}
            for p in projects
        ],
    }
    return prof


def agent_profile(repo: Repository, reg_no: str, lang: str) -> Profile | None:
    agent = repo.get_agent(reg_no)
    if agent is None:
        return None
    src = agent["source"]
    prof = Profile("agent", agent["reg_no"], _name(agent, lang), is_mock=src["is_mock"])
    status = {"active": {"en": "active", "gu": "સક્રિય", "hi": "सक्रिय"},
              "expired": {"en": "expired", "gu": "મુદત પૂરી", "hi": "समाप्त"},
              "revoked": {"en": "revoked", "gu": "રદ", "hi": "रद्द"}}[agent["status"]]
    prof.add("agent_status", lang, [src], name=_name(agent, lang), district=word(agent["district"], lang),
             status=status.get(lang, status["en"]), valid=fmt_date(agent["valid_until"], lang))
    prof.card = {"type": "agent", "name": agent["name"], "reg_no": agent["reg_no"], "district": agent["district"],
                 "status": agent["status"], "valid_until": agent["valid_until"], "is_mock": src["is_mock"],
                 "source": src}
    return prof
