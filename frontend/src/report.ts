import { OCRResult } from "./types";

// Decision-support report handed to partners (newsroom desks, bank fraud teams, exam boards,
// or Fujitsu Frontria engines). Pramaan informs a human decision; it never asks for takedown.
export const REPORT_SCHEMA = "pramaan.verification_report/v1";

const PRIVATE_NAME_RE = /\b(?:Mr\.|Ms\.|Mrs\.|Shri|Smt\.)\s+[A-Z][a-zA-Z]*(?:\s+[A-Z][a-zA-Z]*)*\b/g;

export function maskPrivateNames(text: string | null | undefined): string {
  if (!text) return "";
  return text.replace(PRIVATE_NAME_RE, "the recipient");
}

const DISCLAIMER =
  "Decision support only. An 'unverified' result does not mean the claim is true; " +
  "verify with the issuing authority before acting or publishing.";

function inputType(r: OCRResult): "image" | "pdf" | "audio" | "text" {
  if (r.is_text) return "text";
  if (r.is_audio) return "audio";
  return (r.filename || "").toLowerCase().endsWith(".pdf") ? "pdf" : "image";
}

export function buildReport(r: OCRResult) {
  const gt = r.matches?.ground_truth;
  const now = new Date();
  return {
    schema: REPORT_SCHEMA,
    generator: "Generated by Pramaan, YellowSense Technologies",
    generated_at: now.toISOString(),
    input: {
      type: inputType(r),
      filename: r.is_text ? null : r.filename ?? null,
      sha256: r.image_hash,
      language: r.claim?.claim_language ?? r.transcription?.language ?? r.language ?? null,
      extraction_engine: r.engine_used,
      text: r.final_text,
    },
    verdict: r.verdict
      ? {
          key: r.verdict.verdict_key,
          title: r.verdict.title,
          reason: r.verdict.reason,
          decided_by: r.verdict.decided_by ?? null,
          official_clarification: r.verdict.official_clarification ?? null,
          evidence: r.verdict.evidence_links,
        }
      : null,
    claim: r.claim
      ? {
          canonical_claim_en: maskPrivateNames(r.claim.canonical_claim_en),
          claimed_issuer: r.claim.claimed_issuer,
          claimed_issuer_id: r.claim.claimed_issuer_id ?? null,
          action: r.claim.action,
          effective_date: r.claim.effective_date,
          amounts: r.claim.amounts,
          claim_type: r.claim.claim_type,
        }
      : null,
    document_check: r.forensics
      ? {
          risk_level: r.forensics.risk_level,
          risk_score: r.forensics.risk_score,
          detected_issuer: r.forensics.detected_issuer,
          findings: r.forensics.findings.map((f) => ({
            cue_id: f.cue_id,
            severity: f.severity,
            title: f.title,
            evidence: f.evidence,
          })),
        }
      : null,
    visual_check: r.visual?.analysed
      ? {
          has_seal: r.visual.has_seal,
          has_signature: r.visual.has_signature,
          has_emblem: r.visual.has_emblem,
          editing_software: r.visual.editing_software,
          regions: r.visual.regions,
        }
      : null,
    source_matches: r.matches
      ? {
          retrieval_mode: r.matches.retrieval_mode,
          debunks: r.matches.debunks.map((m) => ({
            doc_id: m.doc_id,
            label: m.label,
            score: m.score,
            url: m.url,
            title: m.title,
          })),
          official: r.matches.official.map((m) => ({
            doc_id: m.doc_id,
            label: m.label,
            score: m.score,
            url: m.url,
            reference_no: m.reference_no ?? null,
          })),
          ground_truth: gt
            ? {
                status: gt.status,
                similarity: gt.similarity,
                record_id: gt.best?.record_id ?? null,
                reference_link: gt.best?.reference_link ?? null,
              }
            : null,
        }
      : null,
    narrative: r.narrative_result?.assigned
      ? {
          cluster_id: r.narrative_result.cluster_id,
          name: r.narrative_result.narrative_name,
          debunks_count: r.narrative_result.debunks_count,
          first_date: r.narrative_result.first_date,
          last_date: r.narrative_result.last_date,
        }
      : null,
    disclaimer: DISCLAIMER,
  };
}

export function buildPlainSummary(r: OCRResult): string {
  const lines: string[] = [];
  lines.push(`Generated by Pramaan, YellowSense Technologies (${new Date().toLocaleString()})`);
  if (r.verdict) {
    lines.push(`Verdict: ${r.verdict.title}`);
    lines.push(`Why: ${r.verdict.reason}`);
    if (r.verdict.official_clarification) {
      lines.push(`Official clarification: ${r.verdict.official_clarification}`);
    }
  }
  if (r.claim?.canonical_claim_en) lines.push(`Claim: ${maskPrivateNames(r.claim.canonical_claim_en)}`);
  if (r.forensics) lines.push(`Document risk: ${r.forensics.risk_level} (${r.forensics.risk_score}/100)`);
  for (const ev of r.verdict?.evidence_links || []) {
    lines.push(`Evidence: ${ev.doc_id}${ev.url ? ` ${ev.url}` : ""}`);
  }
  if (r.narrative_result?.assigned && r.narrative_result.narrative_name) {
    lines.push(
      `Known narrative: ${r.narrative_result.narrative_name} (${r.narrative_result.debunks_count} debunks)`
    );
  }
  lines.push(DISCLAIMER);
  return lines.join("\n");
}

export function downloadFile(filename: string, content: string, mime: string) {
  const url = URL.createObjectURL(new Blob([content], { type: mime }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
